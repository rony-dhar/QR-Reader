private enum class QrType(val label: String, val icon: ImageVector) {
    TEXT("Text", Icons.Rounded.TextFields),
    URL("Link", Icons.Rounded.Link),
    WIFI("Wi-Fi", Icons.Rounded.Wifi),
    EMAIL("Email", Icons.Rounded.Email),
    PHONE("Phone", Icons.Rounded.Phone),
    CONTACT("Contact", Icons.Rounded.Person),
}

private val securityOptions = listOf("WPA/WPA2", "WEP", "None")

@Composable
fun GenerateScreen(vm: MainViewModel) {
    val context = LocalContext.current

    var typeIndex by rememberSaveable { mutableIntStateOf(0) }
    val type = QrType.entries[typeIndex]

    var text by rememberSaveable { mutableStateOf("") }
    var url by rememberSaveable { mutableStateOf("") }
    var ssid by rememberSaveable { mutableStateOf("") }
    var wifiPassword by rememberSaveable { mutableStateOf("") }
    var security by rememberSaveable { mutableIntStateOf(0) }
    var hidden by rememberSaveable { mutableStateOf(false) }
    var emailTo by rememberSaveable { mutableStateOf("") }
    var emailSubject by rememberSaveable { mutableStateOf("") }
    var emailBody by rememberSaveable { mutableStateOf("") }
    var phone by rememberSaveable { mutableStateOf("") }
    var contactName by rememberSaveable { mutableStateOf("") }
    var contactOrg by rememberSaveable { mutableStateOf("") }
    var contactPhone by rememberSaveable { mutableStateOf("") }
    var contactEmail by rememberSaveable { mutableStateOf("") }

    var generated by rememberSaveable { mutableStateOf<String?>(null) }
    val bitmap = remember(generated) {
        generated?.let { runCatching { QrUtils.encode(it) }.getOrNull() }
    }

    /** Builds the text that goes into the QR code, or null if a required field is empty. */
    fun buildPayload(): String? = when (type) {
        QrType.TEXT -> text.trim().ifEmpty { null }
        QrType.URL -> url.trim().ifEmpty { null }?.let { if (it.contains("://")) it else "https://$it" }
        QrType.WIFI ->
            if (ssid.isBlank()) null else QrUtils.wifiPayload(ssid, wifiPassword, security, hidden)
        QrType.EMAIL ->
            if (emailTo.isBlank()) null else buildString {
                append("mailto:").append(emailTo.trim())
                val params = buildList {
                    if (emailSubject.isNotBlank()) add("subject=" + Uri.encode(emailSubject))
                    if (emailBody.isNotBlank()) add("body=" + Uri.encode(emailBody))
                }
                if (params.isNotEmpty()) append("?").append(params.joinToString("&"))
            }
        QrType.PHONE -> phone.trim().ifEmpty { null }?.let { "tel:$it" }
        QrType.CONTACT ->
            if (contactName.isBlank()) null
            else QrUtils.vCard(contactName.trim(), contactOrg.trim(), contactPhone.trim(), contactEmail.trim())
    }

    Column(
        Modifier
            .fillMaxSize()
            .verticalScroll(rememberScrollState())
            .padding(horizontal = 20.dp, vertical = 16.dp),
        verticalArrangement = Arrangement.spacedBy(14.dp),
    ) {
        Text("Create", style = MaterialTheme.typography.headlineMedium, fontWeight = FontWeight.SemiBold)

        Row(
            Modifier.horizontalScroll(rememberScrollState()),
            horizontalArrangement = Arrangement.spacedBy(8.dp),
        ) {
            QrType.entries.forEachIndexed { index, t ->
                FilterChip(
                    selected = index == typeIndex,
                    onClick = { typeIndex = index },
                    label = { Text(t.label) },
                    leadingIcon = { Icon(t.icon, null, Modifier.size(18.dp)) },
                )
            }
        }

        when (type) {
            QrType.TEXT -> Field(text, { text = it }, "Text", singleLine = false, minLines = 3)
            QrType.URL -> Field(url, { url = it }, "Web address", KeyboardType.Uri)
            QrType.WIFI -> {
                Field(ssid, { ssid = it }, "Network name (SSID)")
                if (security != 2) Field(wifiPassword, { wifiPassword = it }, "Password")
                Row(
                    Modifier.horizontalScroll(rememberScrollState()),
                    horizontalArrangement = Arrangement.spacedBy(8.dp),
                ) {
                    securityOptions.forEachIndexed { index, label ->
                        FilterChip(
                            selected = security == index,
                            onClick = { security = index },
                            label = { Text(label) },
                        )
                    }
                }
                Row(verticalAlignment = Alignment.CenterVertically) {
                    Text("Hidden network", Modifier.weight(1f))
                    Switch(checked = hidden, onCheckedChange = { hidden = it })
                }
            }
            QrType.EMAIL -> {
                Field(emailTo, { emailTo = it }, "To", KeyboardType.Email)
                Field(emailSubject, { emailSubject = it }, "Subject")
                Field(emailBody, { emailBody = it }, "Message", singleLine = false, minLines = 3)
            }
            QrType.PHONE -> Field(phone, { phone = it }, "Phone number", KeyboardType.Phone)
            QrType.CONTACT -> {
                Field(contactName, { contactName = it }, "Name")
                Field(contactOrg, { contactOrg = it }, "Company")
                Field(contactPhone, { contactPhone = it }, "Phone", KeyboardType.Phone)
                Field(contactEmail, { contactEmail = it }, "Email", KeyboardType.Email)
            }
        }

        Button(
            onClick = {
                val payload = buildPayload()
                when {
                    payload == null ->
                        Toast.makeText(context, "Fill in the required field first", Toast.LENGTH_SHORT).show()
                    runCatching { QrUtils.encode(payload) }.isFailure -> {
                        generated = payload
                        Toast.makeText(context, "That's too long for a QR code", Toast.LENGTH_SHORT).show()
                    }
                    else -> {
                        generated = payload
                        val now = System.currentTimeMillis()
                        vm.add(
                            ScanRecord(
                                id = now,
                                content = payload,
                                format = "QR Code",
                                kind = QrUtils.kindOfText(payload),
                                source = Source.CREATED,
                                timestamp = now,
                            )
                        )
                    }
                }
            },
            modifier = Modifier.fillMaxWidth().height(52.dp),
            shape = RoundedCornerShape(16.dp),
        ) {
            Text("Generate QR code")
        }

        val content = generated
        if (content != null) {
            if (bitmap != null) {
                Surface(
                    modifier = Modifier.fillMaxWidth(),
                    shape = RoundedCornerShape(24.dp),
                    color = Color.White,
                    border = BorderStroke(1.dp, MaterialTheme.colorScheme.outlineVariant),
                ) {
                    Image(
                        bitmap = bitmap.asImageBitmap(),
                        contentDescription = "Generated QR code",
                        modifier = Modifier.fillMaxWidth().aspectRatio(1f).padding(16.dp),
                    )
                }
                Text(
                    QrUtils.summary(ScanRecord(0, content, "QR Code", "", Source.CREATED, 0)),
                    maxLines = 3,
                    overflow = TextOverflow.Ellipsis,
                    style = MaterialTheme.typography.labelMedium,
                    color = MaterialTheme.colorScheme.onSurfaceVariant,
                )
                Row(horizontalArrangement = Arrangement.spacedBy(10.dp)) {
                    OutlinedButton(
                        onClick = { saveToGallery(context, bitmap) },
                        modifier = Modifier.weight(1f),
                    ) {
                        Icon(Icons.Rounded.Download, null, Modifier.size(18.dp))
                        Spacer(Modifier.width(8.dp))
                        Text("Save")
                    }
                    Button(
                        onClick = { shareBitmap(context, bitmap) },
                        modifier = Modifier.weight(1f),
                    ) {
                        Icon(Icons.Rounded.Share, null, Modifier.size(18.dp))
                        Spacer(Modifier.width(8.dp))
                        Text("Share")
                    }
                }
            } else {
                Text(
                    "This is too long to fit in a QR code. Try something shorter.",
                    color = MaterialTheme.colorScheme.error,
                )
            }
        }
    }
}

@Composable
private fun Field(
    value: String,
    onChange: (String) -> Unit,
    label: String,
    keyboard: KeyboardType = KeyboardType.Text,
    singleLine: Boolean = true,
    minLines: Int = 1,
) {
    OutlinedTextField(
        value = value,
        onValueChange = onChange,
        label = { Text(label) },
        singleLine = singleLine,
        minLines = minLines,
        keyboardOptions = KeyboardOptions(keyboardType = keyboard),
        shape = RoundedCornerShape(14.dp),
        modifier = Modifier.fillMaxWidth(),
    )
}
